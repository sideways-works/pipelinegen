package cli

import (
	"encoding/json"
	"fmt"
	"os"
	"strings"

	"github.com/sideways-works/pipelinegen/internal/config"
	"github.com/sideways-works/pipelinegen/internal/runs"
	"github.com/sideways-works/pipelinegen/plugin"
)

const envTrusted = plugin.EnvTrusted

// trialPinDoc is the guide's section on trying a change's trusted keys
// before it is merged; docscheck checks that it resolves.
const trialPinDoc = "docs/how-to/plugins.md#trying-a-new-pin-before-merging"

const noTrustedKeys = "this pipeline was generated by a tool that does not pin where runs read and write: regenerate it"

// For a proposed change, where its run reads and writes, which credential serves which purpose and which
// binaries run come from the config the pipeline was generated from, never from the change.
func trustChange(cfg *config.Config, ch runs.Change) error {
	if !ch.Proposed() {
		return nil
	}

	if ch.Doubt != "" {
		cfg.Warnings = append([]string{ch.Doubt + ": run as a proposed change, which writes nothing a trusted plan reads"}, cfg.Warnings...)
	}

	blob := os.Getenv(envTrusted)
	if blob == "" {
		// said once, by the plan's status and comment, never by every step.
		cfg.Warnings = append([]string{noTrustedKeys}, cfg.Warnings...)

		return nil
	}

	var t config.Trusted
	if err := json.Unmarshal([]byte(blob), &t); err != nil {
		return fmt.Errorf("%w: %s: %w", errUsage, envTrusted, err)
	}

	if edited := cfg.WithTrusted(t); len(edited) > 0 {
		line := "planned with the repository's own " + strings.Join(edited, ", ") +
			": this change edits them, and they take effect once it is merged; to try them first, see Trying a new pin before merging (" + trialPinDoc + ")"
		cfg.Warnings = append([]string{line}, cfg.Warnings...)
	}

	return nil
}
